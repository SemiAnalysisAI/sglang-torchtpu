"""Save and load PyTorch compiler cache bundles."""

from __future__ import annotations

import functools
import logging
import os
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

import torch
from torch._dynamo.source import AttrSource, GlobalSource, LocalSource
from torch._guards import ChainedSource

logger = logging.getLogger(__name__)


def save(path: Path) -> None:
    """Save all torch.compile artifacts in a bundle.

    This includes Dynamo guards and generated bytecode, which PyTorch normally
    does not cache because caching them reduces safety.
    """

    if path.exists():
        raise FileExistsError(f"torch.compile bundle exists: {path}")

    # PyTorch only flushes cached Dynamo bytecode in precompile mode.
    with torch._dynamo.config.patch(caching_precompile=True):
        result = torch.compiler.save_cache_artifacts()
    if result is None:
        raise RuntimeError("PyTorch produced no compiler artifacts during warmup.")
    serialized, cache_info = result

    from torch._inductor.codecache import write_atomic

    write_atomic(str(path), serialized, make_dirs=True)
    logger.info(
        "Saved torch.compile cache bundle %s (%d bytes, cache_info=%s).",
        path,
        len(serialized),
        cache_info,
    )


def load(path: Path) -> None:
    """Load torch.compile artifacts from a trusted bundle.

    Compiler artifacts use pickle internally and may execute arbitrary code.
    """

    if not path.is_file():
        raise FileNotFoundError(
            f"torch.compile cache bundle does not exist: {path}. Run once with "
            "--unsafe-save-torch-compile-bundle using the same directory and "
            "configuration."
        )
    serialized = path.read_bytes()
    if torch.compiler.load_cache_artifacts(serialized) is None:
        raise RuntimeError(f"torch.compile cache bundle is invalid: {path}")
    logger.info(
        "Loaded torch.compile cache bundle %s (%d bytes).",
        path,
        len(serialized),
    )


def set_fresh_compiler_cache() -> tempfile.TemporaryDirectory[str]:
    """Route this process's compiler caches to a fresh temporary directory.

    Keep the returned directory alive while compiled functions may run.
    """

    cache_dir = tempfile.TemporaryDirectory(prefix="sglang-torch-compile-")
    os.environ["TORCHINDUCTOR_CACHE_DIR"] = cache_dir.name

    from torch._dynamo import package
    from torch._inductor.utils import clear_caches

    clear_caches()
    # Dynamo creates this singleton before the environment change above.
    package.DynamoCache = package.DiskDynamoCache(
        os.path.join(cache_dir.name, "dynamo")
    )
    return cache_dir


class Compiler:
    """Compile a function with cacheable Dynamo guards.

    caching_precompile must also cover calls because torch.compile is lazy.
    """

    def __init__(
        self,
        fn: Callable[..., Any],
        *,
        backend: Any,
        fullgraph: bool,
        dynamic: bool,
    ) -> None:
        with torch._dynamo.config.patch(caching_precompile=True):
            self.compiled = torch.compile(
                fn,
                backend=backend,
                fullgraph=fullgraph,
                dynamic=dynamic,
                options={"guard_filter_fn": _skip_unrestorable_guards_unsafe},
            )
        functools.update_wrapper(self, fn)

    def __call__(self, *args: Any, **kwargs: Any) -> Any:
        with torch._dynamo.config.patch(caching_precompile=True):
            return self.compiled(*args, **kwargs)


def _skip_unrestorable_guards_unsafe(guard_entries: Any) -> list[bool]:
    """Drop guards rooted in transient wrapper and forward-context state."""

    forward_context_global = (
        "__import_sglang_dot_srt_dot_model_executor_dot_forward_context"
    )
    keep = []
    for entry in guard_entries:
        source = entry.orig_guard.originating_source
        chain = []
        while isinstance(source, ChainedSource):
            chain.append(source)
            source = source.base

        transient_fn = isinstance(source, LocalSource) and source.local_name == "fn"
        transient_forward_context = (
            isinstance(source, GlobalSource)
            and source.global_name == forward_context_global
            and any(
                isinstance(chained_source, AttrSource)
                and chained_source.member == "_current"
                for chained_source in chain
            )
        )
        keep.append(not (transient_fn or transient_forward_context))
    return keep
